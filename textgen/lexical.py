"""Lexical distance of the briefs of the variants of one base run.

The writer of a variant echoes its brief: the notes, the summary and the wording of the entity connections come back in the text. When the
briefs of two variants share a run of `n` (9) words, so will their texts. `python -m textgen lexical <base run>` compares the briefs of
`<base>-v01 ... -vNN` (the sentences generated by code - keyword counts - are left out; names, figures and other protected facts of the
knowledge base count as one word) and exits with 1 when two briefs share such a run.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from . import store
from .protected import Mask, protected_phrases
from .shingles import find_duplicates

CODE_SENTENCE = re.compile(r'^(Use "|Use no tracked keyword|Keep the tracked keywords out|The .* (row|list|e-mail address) .*tracked keyword)')
SPLIT = re.compile(r"(?<=[.!?])\s+")


def brief_corpus(brief: dict) -> list[tuple[str, str]]:
    """[(label, text)] of the free-written parts of a brief: intent, and per block summary, notes (without code sentences), connections."""
    out = [("intent", brief.get("intent_summary", ""))]
    for b in brief["blocks"]:
        notes = " ".join(s for s in SPLIT.split(b.get("copywriter_notes", "")) if not CODE_SENTENCE.match(s.strip()))
        conns = ". ".join(f'{c["subject"]} {c["relation"]} {c["object"]}' for c in b.get("entity_connections", []))
        out.append((b["id"], f'{b.get("summary", "")}\n\n{notes}\n\n{conns}'))
    return out


def variant_runs(base: str, runs_dir: Path) -> list[str]:
    return sorted(d.name for d in runs_dir.iterdir() if d.is_dir() and re.fullmatch(re.escape(base) + r"-v\d+", d.name) and (d / store.BRIEF).exists())


def lexical_conflicts(base: str, runs_dir: Path, n: int = 9) -> tuple[dict[str, list[dict]], dict[str, int]]:
    """({variant: shared runs}, {variant: words of free-written brief})."""
    names = variant_runs(base, runs_dir)
    corpus = {nm: brief_corpus(json.loads((runs_dir / nm / store.BRIEF).read_text(encoding="utf-8"))) for nm in names}
    mask = None
    kb_file = runs_dir / base / store.KNOWLEDGE_BASE
    if kb_file.exists():
        from . import kb as KB
        from .inputs import Job

        job = Job(**json.loads((runs_dir / base / store.INPUT).read_text(encoding="utf-8")))
        mask = Mask.for_kb(KB.load(json.loads(kb_file.read_text(encoding="utf-8"))), job.brand_name)
    dups = find_duplicates(corpus, n, mask)
    from .shingles import tokens

    words = {nm: sum(len(tokens(t)) for _, t in blocks) for nm, blocks in corpus.items()}
    return dups, words
